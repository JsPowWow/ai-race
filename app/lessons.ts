/** Урок над одной вкладкой */
export type Lesson = {
  /** Название — как у вкладки */
  title: string;
  /** Чего добиться (проверяемый итог), одной-двумя фразами: её видно сразу под названием */
  goal: string;
  /**
   * Шаги. Первое предложение шага — действие с глагола («Нажми…», «Открой…»), без вопросов: урок показывает его крупно.
   * Галочки запоминаются в браузере по номерам шагов — меняешь шаги, подними LESSONS_VERSION,
   * чтобы старые отметки не встали на новые шаги.
   */
  tasks: string[];
  /**
   * Какое действие отмечает шаг само (по номеру шага; null — только кнопкой «Готово»).
   * Действия шлют вкладки: emit('did', 'exam') и т. п., смена мозга — 'champion:<кто>' (см. app/lesson.tsx)
   */
  auto?: (string | null)[];
  /** Что изучаем: js — про JavaScript, ai — про искусственный интеллект */
  learn: { js: string; ai: string };
  /** Простыми словами */
  theory: string;
  /** Как это скажется на гонке */
  impact: string;
};

