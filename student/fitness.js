//  УРОК 3, ШАГ 1. ФИТНЕС — за что хвалить машину
// ════════════════════════════════════════════════════════════════
//
//  Вызывается для каждой машины, когда поколение закончилось.
//  Чем больше число, тем машина «лучше». Лучшая станет родителем следующего поколения.
//
//  car = {
//    progress     — сколько пикселей проехала вдоль трассы, все круги вместе (лучший результат)
//    trackLength  — длина всего заезда: три круга
//    progressPct  — то же в процентах, 0..100
//    finished     — доехала до финиша
//    crashed      — разбилась (в бордюр или в машину)
//    hitCar       — разбилась именно о машину
//    stalled      — заглохла или крутилась на месте
//    ticks        — сколько тиков ехала (60 тиков = 1 секунда гонки)
//    avgSpeed     — средняя скорость, px за тик
//    topSpeed     — максимальная скорость
//    wiggle       — сколько дёргала руль (чем больше, тем сильнее виляла)
//  }
//
//  Как сейчас: за расстояние, а доехавшим — бонус, и чем быстрее, тем больше.
//  Машина оптимизирует ровно то, что ты посчитал, а не то, что ты имел в виду:
//  без бонуса за время рою всё равно, ползти через медленную зону или нет.

export function fitness(car) {
  let score = car.progress;
  if (car.finished) score += 20000 - car.ticks; // на три круга дают меньше 20 тыс. тиков, так что бонус всегда больше нуля
  return score;
}
